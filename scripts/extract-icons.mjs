// Copies the few game-icons.net icons we use (CC BY 3.0) into src/ui/theme/icons.ts.
// Run with: node scripts/extract-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const set = JSON.parse(
  readFileSync(require.resolve('@iconify-json/game-icons/icons.json'), 'utf8'),
);

const pick = {
  wood: 'pine-tree',
  brick: 'brick-pile',
  sheep: 'sheep',
  wheat: 'wheat',
  ore: 'stone-pile',
  desert: 'cactus',
  harbor: 'anchor',
};

const size = set.width ?? 512;
const lines = Object.entries(pick).map(([key, name]) => {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Missing icon ${name}`);
  return `  ${key}: ${JSON.stringify(icon.body)},`;
});

writeFileSync(
  'src/ui/theme/icons.ts',
  `// Generated by scripts/extract-icons.mjs. Icons by Lorc and Delapouite, game-icons.net, CC BY 3.0.
export const ICON_SIZE = ${size};

export const icons = {
${lines.join('\n')}
} as const;
`,
);
console.log('wrote', Object.keys(pick).length, 'icons, size', size);
